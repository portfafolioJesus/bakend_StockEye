CREATE TABLE public.trabajos (
    secuencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id TEXT NOT NULL UNIQUE CHECK (id ~ '^[0-9a-f]{32}$'),
    sucursal_id INTEGER NOT NULL CHECK (sucursal_id IN (1, 2)),
    relativo TEXT NOT NULL,
    nombre TEXT NOT NULL,
    sha256 TEXT NOT NULL,
    copia TEXT,
    estado TEXT NOT NULL CHECK (estado IN ('pendiente', 'procesando', 'completada', 'error')),
    creado_en TEXT NOT NULL,
    iniciado_en TEXT,
    terminado_en TEXT,
    intentos INTEGER NOT NULL DEFAULT 0 CHECK (intentos >= 0),
    error TEXT,
    UNIQUE (sucursal_id, relativo, sha256)
);
CREATE INDEX cola_estado ON public.trabajos (estado, secuencia);
CREATE TABLE public.observaciones (
    sucursal_id INTEGER NOT NULL CHECK (sucursal_id IN (1, 2)),
    relativo TEXT NOT NULL,
    firma TEXT NOT NULL,
    visto_desde DOUBLE PRECISION NOT NULL,
    registrado BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (sucursal_id, relativo)
);
